-- Sistema de Assistência Técnica — PostgreSQL
-- Execute em um banco vazio: psql -d assistencia_tecnica -f init.sql
BEGIN;

DROP TABLE IF EXISTS sessoes, agendamentos, equipamentos, clientes, usuarios CASCADE;

CREATE TABLE usuarios (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            VARCHAR(120) NOT NULL,
  email           VARCHAR(180) NOT NULL UNIQUE,
  senha_hash      VARCHAR(180) NOT NULL,
  ativo           BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE clientes (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome              VARCHAR(120) NOT NULL,
  email             VARCHAR(180) NOT NULL UNIQUE,
  cpf_criptografado TEXT NOT NULL,
  cpf_hash          CHAR(64) NOT NULL UNIQUE,
  telefone          VARCHAR(25) NOT NULL,
  criado_em         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE equipamentos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id     INTEGER NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  tipo           VARCHAR(80) NOT NULL,
  marca          VARCHAR(80) NOT NULL,
  modelo         VARCHAR(100) NOT NULL,
  numero_serie   VARCHAR(100) NOT NULL UNIQUE,
  descricao      TEXT,
  criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_equipamentos_cliente ON equipamentos(cliente_id);

CREATE TABLE agendamentos (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipamento_id     INTEGER NOT NULL REFERENCES equipamentos(id) ON DELETE RESTRICT,
  data_agendamento   TIMESTAMPTZ NOT NULL,
  descricao          TEXT NOT NULL,
  status             VARCHAR(20) NOT NULL DEFAULT 'agendado'
                     CHECK (status IN ('agendado', 'em_andamento', 'concluido', 'cancelado')),
  criado_em          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_agendamentos_data ON agendamentos(data_agendamento);
CREATE INDEX idx_agendamentos_equipamento ON agendamentos(equipamento_id);

CREATE TABLE sessoes (
  token_hash  CHAR(64) PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_em   TIMESTAMPTZ NOT NULL,
  criada_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_sessoes_expiracao ON sessoes(expira_em);

